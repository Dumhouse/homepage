package inventory

import (
	"context"
	"fmt"
	"strings"
)

// SSHConfig renders a ~/.ssh/config block for every host with a live SSH login
// and a primary address. Multiple logins get name-user aliases.
func (s *Store) SSHConfig(ctx context.Context) (string, error) {
	hosts, err := s.ListHosts(ctx)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Generated by Home Services. Logins only — no keys or passwords.\n\n")
	n := 0
	for i := range hosts {
		h := &hosts[i]
		if len(h.SSH) == 0 || len(h.Addresses) == 0 || h.Lifecycle == "decommissioned" {
			continue
		}
		addr := h.Addresses[0].Address
		for _, a := range h.Addresses {
			if a.IsPrimary {
				addr = a.Address
				break
			}
		}
		for j, x := range h.SSH {
			alias := slugify(h.Name)
			if alias == "" {
				alias = fmt.Sprintf("host-%d", h.ID)
			}
			if j > 0 {
				alias += "-" + slugify(x.User)
			}
			fmt.Fprintf(&b, "Host %s\n  HostName %s\n  User %s\n  Port %d\n\n", alias, addr, x.User, x.Port)
			n++
		}
	}
	if n == 0 {
		return "# No hosts with SSH logins yet.\n", nil
	}
	return b.String(), nil
}
