// Package export renders the inventory in formats other tools read:
// Homepage's services.yaml, an Ansible inventory, Prometheus file-based
// service discovery and a NetBox IP-address import. Nothing secret is
// included — no passwords, keys or vault links.
package export

import (
	"bytes"
	"encoding/csv"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/dawidof/home-services/internal/inventory"
)

// Format describes one export for the settings page.
type Format struct {
	Name        string // URL name, e.g. homepage.yaml
	Title       string
	Description string
	ContentType string
}

var Formats = []Format{
	{"homepage.yaml", "Homepage services.yaml", "Every web service grouped by location, with links and site monitors — paste into (or mount as) Homepage's services.yaml. It's a separate file: your existing dashboard isn't touched.", "text/yaml; charset=utf-8"},
	{"ansible.yaml", "Ansible inventory", "Hosts with ansible_host/user/port, grouped by location, kind and tag (loc_*, kind_*, tag_*). Use with ansible -i.", "text/yaml; charset=utf-8"},
	{"prometheus.json", "Prometheus targets", "file_sd_configs targets for hosts with a service on port 9100 (node_exporter). Change the port with ?port=, or ?all=1 for every host.", "application/json"},
	{"netbox-ips.csv", "NetBox IP addresses", "CSV for NetBox → IPAM → IP Addresses → Bulk import: every address with its host as description.", "text/csv; charset=utf-8"},
}

// Find returns the format with that name.
func Find(name string) (Format, bool) {
	for _, f := range Formats {
		if f.Name == name {
			return f, true
		}
	}
	return Format{}, false
}

// Options tune an export (only Prometheus uses them today).
type Options struct {
	Port int
	All  bool
}

// Render builds the export from full hosts (with services and SSH).
func Render(name string, hosts []inventory.Host, o Options) ([]byte, error) {
	live := make([]inventory.Host, 0, len(hosts))
	for _, h := range hosts {
		if h.Lifecycle != "decommissioned" {
			live = append(live, h)
		}
	}
	switch name {
	case "homepage.yaml":
		return homepage(live), nil
	case "ansible.yaml":
		return ansible(live), nil
	case "prometheus.json":
		return prometheus(live, o)
	case "netbox-ips.csv":
		return netbox(live)
	}
	return nil, fmt.Errorf("unknown export %q", name)
}

// q quotes a YAML scalar (a JSON string is valid YAML).
func q(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func slug(s string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
			dash = false
		case !dash && b.Len() > 0:
			b.WriteByte('_')
			dash = true
		}
	}
	return strings.TrimSuffix(b.String(), "_")
}

// Primary is the address used to reach a host: the primary one, else LAN,
// else the first.
func Primary(h inventory.Host) string {
	for _, a := range h.Addresses {
		if a.IsPrimary {
			return a.Address
		}
	}
	for _, a := range h.Addresses {
		if a.Kind == "lan" {
			return a.Address
		}
	}
	if len(h.Addresses) > 0 {
		return h.Addresses[0].Address
	}
	return ""
}

func location(h inventory.Host) string {
	if h.Location != nil && h.Location.Name != "" {
		return h.Location.Name
	}
	return ""
}

// serviceURL is how a person opens a service, "" for non-web services.
func serviceURL(h inventory.Host, s inventory.Service) string {
	path := s.Path
	if path != "" && !strings.HasPrefix(path, "/") {
		path = "/" + path
	}
	if s.Domain != "" {
		return "https://" + s.Domain + path
	}
	addr := Primary(h)
	if addr == "" || s.Port == 0 {
		return ""
	}
	switch s.Protocol {
	case "http", "https":
		if strings.Contains(addr, ":") {
			addr = "[" + addr + "]"
		}
		return fmt.Sprintf("%s://%s:%d%s", s.Protocol, addr, s.Port, path)
	}
	return ""
}

func homepage(hosts []inventory.Host) []byte {
	groups := map[string][]string{}
	order := []string{}
	for _, h := range hosts {
		g := location(h)
		if g == "" {
			g = "Services"
		}
		for _, s := range h.Services {
			u := serviceURL(h, s)
			if u == "" {
				continue
			}
			if _, ok := groups[g]; !ok {
				order = append(order, g)
			}
			var e strings.Builder
			fmt.Fprintf(&e, "    - %s:\n        href: %s\n        description: %s\n        siteMonitor: %s\n", q(s.Name), q(u), q("on "+h.Name), q(u))
			if s.Type != "" {
				fmt.Fprintf(&e, "        icon: %s\n", q(strings.ToLower(strings.ReplaceAll(s.Type, " ", "-"))+".png"))
			}
			groups[g] = append(groups[g], e.String())
		}
	}
	sort.Strings(order)
	var b bytes.Buffer
	b.WriteString("# Homepage services.yaml — generated by Home Services. Web services only; no secrets.\n")
	if len(order) == 0 {
		b.WriteString("# No web services yet (give a service a domain, or protocol http/https and a port).\n[]\n")
	}
	for _, g := range order {
		fmt.Fprintf(&b, "- %s:\n", q(g))
		for _, e := range groups[g] {
			b.WriteString(e)
		}
	}
	return b.Bytes()
}

func ansible(hosts []inventory.Host) []byte {
	var b bytes.Buffer
	b.WriteString("# Ansible inventory — generated by Home Services. Logins only; no keys or passwords.\nall:\n  hosts:\n")
	children := map[string][]string{}
	names := map[int64]string{}
	used := map[string]bool{}
	n := 0
	for _, h := range hosts {
		addr := Primary(h)
		if addr == "" {
			continue
		}
		name := slug(h.Name)
		if name == "" || used[name] {
			name = fmt.Sprintf("%s_%d", orDefault(name, "host"), h.ID)
		}
		used[name] = true
		names[h.ID] = name
		n++
		fmt.Fprintf(&b, "    %s:\n      ansible_host: %s\n", name, q(addr))
		if len(h.SSH) > 0 {
			fmt.Fprintf(&b, "      ansible_user: %s\n", q(h.SSH[0].User))
			if h.SSH[0].Port != 0 && h.SSH[0].Port != 22 {
				fmt.Fprintf(&b, "      ansible_port: %d\n", h.SSH[0].Port)
			}
		}
		if l := location(h); l != "" {
			children["loc_"+slug(l)] = append(children["loc_"+slug(l)], name)
		}
		if h.Kind != "" {
			children["kind_"+h.Kind] = append(children["kind_"+h.Kind], name)
		}
		for _, t := range h.Tags {
			if s := slug(t); s != "" && t != "proposed" {
				children["tag_"+s] = append(children["tag_"+s], name)
			}
		}
	}
	if n == 0 {
		b.WriteString("    {}\n")
	}
	if len(children) > 0 {
		b.WriteString("  children:\n")
		keys := make([]string, 0, len(children))
		for k := range children {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "    %s:\n      hosts:\n", k)
			for _, h := range children[k] {
				fmt.Fprintf(&b, "        %s: {}\n", h)
			}
		}
	}
	return b.Bytes()
}

func prometheus(hosts []inventory.Host, o Options) ([]byte, error) {
	if o.Port == 0 {
		o.Port = 9100
	}
	type group struct {
		Targets []string          `json:"targets"`
		Labels  map[string]string `json:"labels"`
	}
	out := []group{}
	for _, h := range hosts {
		addr := Primary(h)
		if addr == "" {
			continue
		}
		has := o.All
		for _, s := range h.Services {
			has = has || s.Port == o.Port
		}
		if !has {
			continue
		}
		if strings.Contains(addr, ":") {
			addr = "[" + addr + "]"
		}
		labels := map[string]string{"host": h.Name, "kind": h.Kind}
		if l := location(h); l != "" {
			labels["location"] = l
		}
		out = append(out, group{Targets: []string{addr + ":" + strconv.Itoa(o.Port)}, Labels: labels})
	}
	return json.MarshalIndent(out, "", "  ")
}

func netbox(hosts []inventory.Host) ([]byte, error) {
	var b bytes.Buffer
	w := csv.NewWriter(&b)
	_ = w.Write([]string{"address", "status", "dns_name", "description"})
	for _, h := range hosts {
		for _, a := range h.Addresses {
			mask := "/32"
			if strings.Contains(a.Address, ":") {
				mask = "/128"
			}
			addr := a.Address
			if !strings.Contains(addr, "/") {
				addr += mask
			}
			if !strings.ContainsAny(a.Address, ".:") {
				continue // a name, not an IP
			}
			_ = w.Write([]string{addr, "active", h.Hostname, h.Name + " (" + a.Kind + ")"})
		}
	}
	w.Flush()
	return b.Bytes(), w.Error()
}

func orDefault(v, def string) string {
	if v == "" {
		return def
	}
	return v
}
